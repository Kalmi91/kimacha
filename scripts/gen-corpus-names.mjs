#!/usr/bin/env node
/**
 * gen-corpus-names.mjs, writes lib/corpusNames.ts: the proper names of the corpus, per language.
 *
 * The "learned words only" gate (lib/knownSentence.ts) takes a capitalised word INSIDE a sentence as a name.
 * A word at the START of a sentence is capitalised anyway, so it is a name only when it is on this list:
 * the corpus writes it with a capital inside a sentence somewhere else, and never in lowercase
 * (Paz / paz, Will / will stay out: they are ordinary words too).
 *
 * Corpus = the target-language sentences: the `sentence_<lang>` fields of data/words* and the
 * `<lang>` texts of the story sentences (data/practice/stories*.json).
 * The capital rule is lib/properNames.ts (capitalizedWords); lib/__tests__/properNames.test.ts fails when this copy drifts.
 *
 * Run: npm run gen:names            (rewrites lib/corpusNames.ts)
 *      node scripts/gen-corpus-names.mjs --check   (exit 1 if lib/corpusNames.ts is out of date)
 */

import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'lib', 'corpusNames.ts');
const check = process.argv.includes('--check');
const LANGS = ['es', 'en', 'hu'];

// same rule as lib/properNames.ts
const OPENER = /["“«¿¡(‘'[]/;
const SENTENCE_END = /[.!?…:]/;
const EDGE = /^([^A-Za-z0-9À-ɏ]*)(.*?)([^A-Za-z0-9À-ɏ]*)$/;
function words(sentence) {
  const found = [];
  let atStart = true;
  for (const chunk of sentence.split(/\s+/)) {
    if (!chunk) continue;
    const [, lead, word, trail] = EDGE.exec(chunk);
    const initial = atStart || OPENER.test(lead);
    if (word) found.push({ word, initial, capital: word[0] !== word[0].toLowerCase() });
    atStart = SENTENCE_END.test(word ? trail : chunk) || (!word && atStart);
  }
  return found;
}

const sentences = { es: [], en: [], hu: [] };
function walk(value, file) {
  if (Array.isArray(value)) return value.forEach((v) => walk(v, file));
  if (!value || typeof value !== 'object') return;
  for (const [key, v] of Object.entries(value)) {
    const own = /^sentence_(es|en|hu)$/.exec(key);
    if (own && typeof v === 'string') sentences[own[1]].push(v);
    else if (/stories[^/\\]*\.json$/.test(file) && LANGS.includes(key) && typeof v === 'string') sentences[key].push(v);
    else walk(v, file);
  }
}
function scan(dir) {
  for (const name of readdirSync(dir).sort()) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) scan(path);
    else if (name.endsWith('.json')) walk(JSON.parse(readFileSync(path, 'utf8')), path);
  }
}
scan(join(root, 'data', 'words'));
scan(join(root, 'data', 'words-open'));
scan(join(root, 'data', 'practice'));

const quote = (s) => (s.includes("'") ? JSON.stringify(s) : `'${s}'`);
const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const lines = LANGS.map((lang) => {
  const inside = new Set();
  const lower = new Set();
  for (const sentence of sentences[lang]) {
    for (const w of words(sentence)) {
      const key = w.word.toLowerCase();
      if (!w.capital) lower.add(key);
      else if (!w.initial) inside.add(key);
    }
  }
  const names = [...inside].filter((n) => !lower.has(n) && n.length > 1).sort(byCode);
  const rows = [];
  let row = '  ';
  for (const n of names) {
    const item = `${quote(n)}, `;
    if (row.length + item.length > 112) {
      rows.push(row.trimEnd());
      row = '  ';
    }
    row += item;
  }
  if (row.trim()) rows.push(row.trimEnd());
  return [`  ${lang}: [`, ...rows.map((r) => `  ${r}`), '  ],'];
});

const content = [
  `// GENERATED by scripts/gen-corpus-names.mjs (npm run gen:names), do not edit.`,
  `// The words the corpus writes with a capital INSIDE a sentence and never in lowercase, per language (lowercased).`,
  `// lib/knownSentence.ts takes a capitalised word at the start of a sentence as a name only when it is here.`,
  ``,
  `export const CORPUS_NAMES: Record<'es' | 'en' | 'hu', string[]> = {`,
  ...lines.flat(),
  `};`,
  ``,
].join('\n');

const before = existsSync(out) ? readFileSync(out, 'utf8') : '';
if (check) {
  if (content !== before) {
    console.error('corpusNames.ts is out of date, run: npm run gen:names');
    process.exit(1);
  }
} else if (content !== before) {
  writeFileSync(out, content);
  console.log('wrote lib/corpusNames.ts');
}
