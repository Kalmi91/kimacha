const filePath = path.join(__dirname, '..', 'data', 'words.ts');
let content = fs.readFileSync(filePath, 'utf-8');

let count = 0;
for (const [word, withArticle] of Object.entries(articles)) {
  const escaped = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const regex = new RegExp(`es: '${escaped}'`, 'g');
  if (content.match(regex)) {
    content = content.replace(regex, `es: '${withArticle}'`);
    count++;
  }
}

fs.writeFileSync(filePath, content);
console.log(`Updated ${count} words with articles.`);
