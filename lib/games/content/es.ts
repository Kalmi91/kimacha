// Issue #3: registration of the Spanish lane's game content.
//
// Previously all eight `…ByLang` maps and their sixty JSON imports lived
// in a single file, `lib/games/content.ts`. Two language lanes would thus
// have edited the same lines for every new piece of content. From now on
// one language = one bundle file like this, and `content.ts` only stitches them together:
// a new language = a new file + one line in the `BUNDLES` table.
//
// The types come in via `import type`, so there is no circular import at
// runtime towards `content.ts`, only a compile-time reference.

import type {
  GrammarIndexEntry,
  GrammarTopicData,
  LanguageContentBundle,
} from '../content';
import type { LessonV2 } from '@/lib/grammar/lessonTypes';
import { ES_GRAMMAR_INDEX } from './es.index';
import { ES_GRAMMAR_HU } from './es.hu.index';
import { withHuIndex } from '@/lib/grammar/huOverlay';

// The lessons themselves are registered in es.index.ts (generated by
// scripts/gen-content-index.mjs, `npm run gen:content`) and are lazy: a lesson's JSON is
// parsed on its first getGrammarTopic(), not when the app or a test file loads.
// The order of es.index.ts is the learning order (A1 first, then A2, ...);
// lib/grammar/syllabus.ts is the map that groups these into units and says which ones
// are still unwritten.
//
// The Hungarian sidecars (es.hu.index.ts, data/games/grammar-hu/es) are laid over each lesson as it loads
// (lib/grammar/huOverlay.ts), before the wrapper below.
//
// Wrapped lessons: every noun in the app also as an el / la exercise
// (lib/grammar/nounArticles.ts). nounArticles is required here, not imported, so the word
// JSON it holds stays unparsed until that lesson is first loaded.
const WRAPPERS: Record<string, (lesson: LessonV2) => LessonV2> = {
  'articulos-genero': (lesson) => {
    // eslint-disable-next-line @typescript-eslint/no-require-imports
    const nounArticles: typeof import('@/lib/grammar/nounArticles') = require('@/lib/grammar/nounArticles');
    return nounArticles.withArticleNouns(lesson);
  },
};

const grammarIndex: GrammarIndexEntry[] = withHuIndex(ES_GRAMMAR_INDEX, ES_GRAMMAR_HU).map((entry) => {
  const wrap = WRAPPERS[entry.id];
  return wrap ? { id: entry.id, load: () => wrap(entry.load() as LessonV2) as GrammarTopicData } : entry;
});

// Play cut: the Games/Átbeszélő tabs and their
// data/games/{ccat,myths,chats,stories,confusables} folders were removed. The
// Play cut also trimmed the `LanguageContentBundle` fields down to this
// one: stories/chats/confusables/myths/ccat* are gone, the grammar registry remains.
export const esContent: LanguageContentBundle = { grammarIndex };
